package ud3;

public class H2Ej6 {

	public static void main(String[] args) {
		// Que imprima la suma de todos los números que van del 1 al 100.
		// Definimos variables
		
		int cont=0;
		
		// Mientras que el contador sea menor que 100
		while (cont < 100) {
			// Añadir +1 al contador hasta que llegue a 100
			cont = cont + 1;
			System.out.print(cont+" ");
		}

	}

}
